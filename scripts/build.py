#!/usr/bin/env python3
"""Bundle the audited local modules. Only the existing entrypoint may be queued for explicit teleport following."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
def build():
    blocks = ['-- Generated by scripts/build.py; edit src/*.lua, then rebuild.\n'
              '-- [K] AA Rukia v7: offline-tested; live Roblox / Delta UNVERIFIED.\n'
              'local __modules = {}\n']
    modules = ('core', 'inventory', 'trial', 'team', 'autoplay', 'navigation', 'dungeon', 'session', 'runtime', 'roblox', 'ui')
    for name in modules:
        source = (ROOT / 'src' / f'{name}.lua').read_text()
        for dependency in modules:
            source = source.replace(f"require('./{dependency}')", f'__modules.{dependency}')
        blocks.append(f'__modules.{name} = (function()\n{source}\nend)()\n')
    entry = (ROOT / 'src' / 'entry.lua').read_text()
    for name in modules:
        entry = entry.replace(f"require('./{name}')", f'__modules.{name}')
    blocks.append(entry)
    return '\n'.join(blocks)

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = build()
    target = ROOT / 'main.lua'
    if args.check:
        assert target.read_text() == output, 'main.lua is out of date; run python3 scripts/build.py'
        print('Bundle is reproducible')
    else:
        target.write_text(output)
        print(f'Built main.lua: {len(output.encode())} bytes')
